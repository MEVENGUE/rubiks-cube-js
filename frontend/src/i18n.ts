const STORAGE_KEY = 'rubik-graph-lang'

function detectLang(): Lang {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved && saved in packs) return saved as Lang
  const code = navigator.language.toLowerCase()
  const hit = LANGS.find((item) => code === item.id || code.startsWith(`${item.id}-`))
  return hit?.id ?? 'fr'
}

let lang: Lang = detectLang()

export function getLang() {
  return lang
}

export function t(key: MsgKey, vars?: Record<string, string | number>) {
  const raw = packs[lang][key] ?? packs.fr[key]
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}

export function applyDom() {
  const root = document.documentElement
  root.lang = lang
  root.dir = lang === 'ar' ? 'rtl' : 'ltr'
  document.title = t('pageTitle')
  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n as MsgKey
    el.textContent = t(key)
  })
  document.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => {
    const key = el.dataset.i18nHtml as MsgKey
    el.innerHTML = t(key)
  })
  document.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => {
    const key = el.dataset.i18nTitle as MsgKey
    el.title = t(key)
  })
  document.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => {
    const key = el.dataset.i18nAria as MsgKey
    el.setAttribute('aria-label', t(key))
  })
}

export function initI18n(select: HTMLSelectElement, onChange: () => void) {
  for (const item of LANGS) {
    const opt = document.createElement('option')
    opt.value = item.id
    opt.textContent = item.label
    select.append(opt)
  }
  select.value = lang
  select.addEventListener('change', () => {
    const next = select.value as Lang
    if (!(next in packs)) return
    lang = next
    localStorage.setItem(STORAGE_KEY, next)
    applyDom()
    onChange()
  })
  applyDom()
  onChange()
}
